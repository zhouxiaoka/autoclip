#!/usr/bin/env python3
"""Generate the telemetry provider enum from backend/presets/provider_presets.json (single source).

Rewrites the generated blocks in frontend successRateContract.ts / workflow.ts and the
``provider`` enum in both event_catalog.json copies. ``--check`` fails when any is stale.
Backend reads the JSON directly (backend.core.provider_presets.telemetry_provider_slugs).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESETS = ROOT / 'backend/presets/provider_presets.json'
EXTRA = ('compatible', 'other')
ASR = ('whisper_local', 'sensevoice_local', 'cloud')
CONTRACT = ROOT / 'frontend/src/analytics/successRateContract.ts'
WORKFLOW = ROOT / 'frontend/src/analytics/workflow.ts'
CATALOGS = (ROOT / 'docs/analytics/event_catalog.json', ROOT / 'backend/core/event_catalog.json')


def slugs() -> list[str]:
    return list(json.loads(PRESETS.read_text(encoding='utf-8'))['providers']) + list(EXTRA)


def _ts_list(items) -> str:
    return ', '.join(f"'{item}'" for item in items)


def render() -> dict[Path, str]:
    values = slugs()
    out = {}
    text = CONTRACT.read_text(encoding='utf-8')
    text = re.sub(r"export const TELEMETRY_PROVIDERS = \[(?:.|\n)*?\] as const",
                  f"export const TELEMETRY_PROVIDERS = [\n  // generated by scripts/gen_provider_slugs.py from provider_presets.json\n  {_ts_list(values)},\n] as const", text, count=1)
    out[CONTRACT] = text
    text = WORKFLOW.read_text(encoding='utf-8')
    text = re.sub(r"    provider: \[[^\]]*\],", f"    provider: [{_ts_list(values + list(ASR))}],", text, count=1)
    out[WORKFLOW] = text
    for path in CATALOGS:
        data = json.loads(path.read_text(encoding='utf-8'))
        top = next(k for k, v in data.items() if isinstance(v, dict) and isinstance(v.get('provider'), list))
        data[top]['provider'] = values
        out[path] = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    return out


def main(argv) -> int:
    stale = [path for path, text in render().items() if path.read_text(encoding='utf-8') != text]
    if '--check' in argv:
        for path in stale:
            print(f'stale provider enum: {path.relative_to(ROOT)}', file=sys.stderr)
        return 1 if stale else 0
    for path, text in render().items():
        path.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
