const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../..')

test('the diagnostics notice is a non-modal disclosure and dismissal does not save', () => {
  const app = fs.readFileSync(path.join(root, 'frontend/src/App.tsx'), 'utf8')
  const notice = fs.readFileSync(path.join(root, 'frontend/src/features/diagnostics/DiagnosticsNotice.tsx'), 'utf8')
  const css = fs.readFileSync(path.join(root, 'frontend/src/ui/ac.css'), 'utf8')
  assert.match(app, /<DiagnosticsNotice \/>/)
  assert.doesNotMatch(notice, /from '..\/..\/ui'[\s\S]*Dialog/)
  assert.doesNotMatch(notice, /aria-modal="true"/)
  assert.doesNotMatch(notice, /ac-dialog-backdrop/)
  assert.match(notice, /dismissedThisSession/)
  assert.match(notice, /role="region"/)
  assert.match(notice, /\{t\('允许'\)\}/)
  assert.match(notice, /\{t\('设置'\)\}/)
  assert.match(notice, /variant="cta"/)
  assert.match(notice, /ac-btn--quiet/)
  assert.doesNotMatch(notice, /允许并继续/)
  assert.doesNotMatch(notice, /<Switch/)
  assert.match(notice, /navigate\('\/settings\?section=diagnostics'\)/)
  assert.match(css, /\.ac-diagnostics-notice \{[\s\S]*position: fixed; right: 16px; bottom: 16px;/)
  const dismiss = notice.slice(notice.indexOf('const dismiss'), notice.indexOf('const allow'))
  assert.match(dismiss, /dismissedThisSession = true/)
  assert.doesNotMatch(dismiss, /setConsent/)
  const settings = notice.slice(notice.indexOf('const openSettings'), notice.indexOf('if (!open ||'))
  assert.match(settings, /section=diagnostics/)
  assert.doesNotMatch(settings, /setConsent/)
  const settingsPage = fs.readFileSync(path.join(root, 'frontend/src/pages/SettingsPage.tsx'), 'utf8')
  assert.match(settingsPage, /diagnostics: \{ section: 'app', anchor: 'diagnostics-settings' \}/)
  assert.match(settingsPage, /id="diagnostics-settings"/)
  assert.match(settingsPage, /关闭自动发送/)
})
